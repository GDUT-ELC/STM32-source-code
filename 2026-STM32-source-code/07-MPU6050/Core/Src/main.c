/**
  * @brief  初始化OLED和MPU6050，并循环显示六轴原始数据
  * @param  None
  * @retval 正常运行不返回
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  /* USER CODE BEGIN 2 */
  oled_init();

  if (MPU6050_Init() == HAL_OK)
  {
    MPU6050_Ready = 1U;
    oled_showstring(1, 1, "MPU6050 TEST");
  }
  else
  {
    oled_showstring(1, 1, "MPU6050 ERROR");
    oled_showstring(2, 1, "CHECK I2C");
  }
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    if (MPU6050_Ready != 0U)
    {
      if (MPU6050_GetData(&AX, &AY, &AZ, &GX, &GY, &GZ) == HAL_OK)
      {
        oled_showstring(1, 1, "MPU6050 TEST ");
        oled_showsignednum(2, 1, AX, 5);
        oled_showsignednum(3, 1, AY, 5);
        oled_showsignednum(4, 1, AZ, 5);
        oled_showsignednum(2, 8, GX, 5);
        oled_showsignednum(3, 8, GY, 5);
        oled_showsignednum(4, 8, GZ, 5);
      }
      else
      {
        oled_showstring(1, 1, "MPU6050 ERROR");
      }
    }

    /* 约50Hz刷新，避免主循环无间隔地占用软件I2C和OLED。 */
    HAL_Delay(20U);
  }
  /* USER CODE END 3 */
}

